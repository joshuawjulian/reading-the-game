"""Render planning/CURRICULUM.md from data1.py/data2.py (+ tail.md) and validate the plan.

Usage: python gen.py <output.md>

Validation (exit 1 on any error):
- chapter IDs unique; every prerequisite exists and comes earlier;
- every term name AND alias has exactly one home (case-insensitive);
- 3-8 objectives per chapter; at most 4 animations per chapter (AUTHORING §4);
- every chapter ID mentioned in objectives, notes, forward refs, see-also, diagrams, and drills exists.
"""
import sys, re, collections
