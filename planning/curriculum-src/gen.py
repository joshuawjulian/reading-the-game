def sortkey(t):
    s = t.lower()
    s = re.sub(r"^[^a-z0-9]+", "", s)
    return s
entries = [(name, cid, aliases, None) for (cid, name, aliases) in term_home.values()] + \
          [(a, cid, [], head) for (cid, a, head) in alias_home.values()]
groups = collections.OrderedDict()
for name, cid, aliases, head in sorted(entries, key=lambda e: sortkey(e[0])):
    first = sortkey(name)[0].upper()
    if first.isdigit():
        first = "0-9"
    groups.setdefault(first, []).append((name, cid, aliases, head))
for g, items in groups.items():
    w(f"**{g}**")
    w("")
    for name, cid, aliases, head in items:
        if head:
            w(f"- {name}: see *{head}* -> {cid}")
        elif aliases:
            w(f"- {name} (also: {', '.join(aliases)}) -> {cid}")
        else:
            w(f"- {name} -> {cid}")
