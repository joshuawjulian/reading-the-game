WORDS_PER_UNIT = 375  # 'pages' in the data are a planning size unit; rendered as words (AUTHORING §2 governs length)

ids = [c["id"] for c in CH]
assert len(ids) == len(set(ids)), "dup ids"
order = {cid: i for i, cid in enumerate(ids)}
byid = {c["id"]: c for c in CH}


def split_term(t):
    """'quarters | Cover 4' -> ('quarters', ['Cover 4'])."""
    parts = [p.strip() for p in t.split("|")]
    return parts[0], [p for p in parts[1:] if p]


def words(units):
    return int(round(units * WORDS_PER_UNIT / 500.0)) * 500


def fmt_words(n):
    return f"{n:,}"


# ---- validation
errs = []
term_home = {}   # lower name -> (cid, name, aliases)
alias_home = {}  # lower alias -> (cid, alias, name)
seen = {}        # lower name-or-alias -> description, for collision checks
IDREF = re.compile(r"(?<![\d-])((?:0[1-9]|1[0-5])-\d{2})(?![\d-])")
for c in CH:
    for p in c["prereq"]:
        if p not in order:
            errs.append(f"{c['id']}: unknown prereq {p}")
        elif order[p] >= order[c["id"]]:
            errs.append(f"{c['id']}: prereq {p} not earlier")
    for t in c["terms"]:
        name, aliases = split_term(t)
        for label, kind in [(name, "term")] + [(a, "alias") for a in aliases]:
            k = label.lower()
            if k in seen:
                errs.append(f"dup {kind} '{label}' in {c['id']} (already {seen[k]})")
            seen[k] = f"{kind} in {c['id']}"
        term_home[name.lower()] = (c["id"], name, aliases)
        for a in aliases:
            alias_home[a.lower()] = (c["id"], a, name)
    if not (3 <= len(c["obj"]) <= 8):
        errs.append(f"{c['id']}: {len(c['obj'])} objectives")
    n_anim = sum(1 for d in c["diagrams"] if d.startswith("A:"))
    if n_anim > 4:
        errs.append(f"{c['id']}: {n_anim} animations (AUTHORING §4 caps at ~4)")
    for s in c["see"]:
        if s not in order:
            errs.append(f"{c['id']}: unknown see-also {s}")
    texts = c["obj"] + c["notes"] + c["fwd"] + c["diagrams"] + [c["drill"]]
    for txt in texts:
        for ref in IDREF.findall(txt):
            if ref not in order:
                errs.append(f"{c['id']}: text mentions unknown chapter {ref}: {txt[:70]}")
if errs:
    print("\n".join(errs)); sys.exit(1)

